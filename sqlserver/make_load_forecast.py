"""
Write the SQL Server load of the forecast tables (release 5, Dashboard #5, Seats to Fill).

The forecast runs in Python on the DuckDB warehouse (forecast/run_forecast.py) and writes its
tables to data/marts/. SQL Server receives them the way it receives any source: landed as text,
then typed. Both scripts are generated from the tables themselves, so they stay in step.

    python forecast/run_forecast.py           # the tables
    python sqlserver/make_load_forecast.py    # writes 02b_load_forecast.sql and 03e_build_dw_forecast.sql

  02b_load_forecast.sql      raw.<table>: every forecast CSV as NVARCHAR text (BULK INSERT)
  03e_build_dw_forecast.sql  fc.<table>: the same tables typed, plus the report calendar
"""

from __future__ import annotations

import csv
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]
MARTS = ROOT / "data" / "marts"
DB = ROOT / "warehouse" / "arcadia.duckdb"
TABLES = ["mart_pid_fill_quarter", "mart_fill_survival", "mart_pid_forecast_draws", "mart_pid_forecast_backtest",
          "mart_pid_forecast_accuracy", "mart_pid_forecast_model", "mart_pid_forecast_run", "mart_cw_budget_function"]
CALENDAR = {"ref_report_calendar": "report_calendar", "ref_report_quarter": "report_quarter"}

LOAD_HEADER = """/*
  02b_load_forecast.sql  (generated by sqlserver/make_load_forecast.py; do not edit by hand)
  Release 5: lands the forecast tables Python wrote to data/marts/ into the raw schema as text,
  like every other source. Types are applied in 03e_build_dw_forecast.sql.
*/
SET NOCOUNT ON;
USE ArcadiaHR;
GO
"""

BUILD_HEADER = """/*
  03e_build_dw_forecast.sql  (generated by sqlserver/make_load_forecast.py; do not edit by hand)
  Release 5 (Dashboard #5, Seats to Fill): the forecast tables, typed, in schema fc, with the
  report calendar the page reads its labels from. Column names are the CSVs', so a workbook built
  on SQL Server can be repointed to the CSVs with Data > Replace Data Source.
*/
SET NOCOUNT ON;
USE ArcadiaHR;
GO
IF SCHEMA_ID('fc') IS NULL EXEC('CREATE SCHEMA fc');
GO
"""


def sql_type(duck: str, longest: int) -> str:
    if duck in ("BIGINT", "INTEGER", "HUGEINT"):
        return "INT"
    if duck == "DOUBLE" or duck.startswith("DECIMAL"):
        return "FLOAT"
    if duck == "BOOLEAN":
        return "BIT"
    if duck == "DATE":
        return "DATE"
    return f"VARCHAR({max(10, ((longest + 9) // 10) * 10)})"


def cast(col: str, t: str) -> str:
    if t == "BIT":
        return f"CAST(CASE LOWER([{col}]) WHEN 'true' THEN 1 WHEN 'false' THEN 0 END AS BIT)"
    if t == "DATE":
        return f"CONVERT(DATE, NULLIF([{col}], ''))"
    return f"CAST(NULLIF([{col}], '') AS {t})"


def load_block(table: str, folder: str, columns: list[str]) -> str:
    width = max(len(c) for c in columns) + 2
    cols = ",\n".join(f"    [{c}]{' ' * (width - len(c) - 2)} NVARCHAR(400) NULL" for c in columns)
    pad = " " * max(1, 36 - len(f"raw.{table}"))
    return f"""
DROP TABLE IF EXISTS raw.{table};
CREATE TABLE raw.{table} (
{cols}
);
BULK INSERT raw.{table}
FROM '/repo/data/{folder}/{table}.csv'
WITH (FIRSTROW = 2, FIELDTERMINATOR = ',', ROWTERMINATOR = '0x0a', TABLOCK);
DECLARE @n_{table} INT = (SELECT COUNT(*) FROM raw.{table});
PRINT CONCAT('raw.{table}', '{pad}', @n_{table}, ' rows');
GO
"""


def typed_block(src: str, dst: str, columns: list[tuple[str, str]]) -> str:
    width = max(len(cast(c, t)) for c, t in columns) + 2
    sel = ",\n".join(f"    {cast(c, t)}{' ' * (width - len(cast(c, t)))}AS [{c}]" for c, t in columns)
    return f"""
DROP TABLE IF EXISTS fc.{dst};
SELECT
{sel}
INTO fc.{dst}
FROM raw.{src};
GO
"""


def main():
    con = duckdb.connect(str(DB), read_only=True)
    load, build = [LOAD_HEADER], [BUILD_HEADER]
    counts = []
    for t in TABLES:
        path = MARTS / f"{t}.csv"
        text = path.read_text()
        assert '"' not in text, f"{path.name} holds quoted values; BULK INSERT needs plain fields"
        rows = list(csv.reader(text.splitlines()))
        header = rows[0]
        duck = dict(con.execute(f"SELECT column_name, data_type FROM information_schema.columns "
                                f"WHERE table_schema = 'forecast' AND table_name = '{t}'").fetchall())
        types = []
        for i, c in enumerate(header):
            longest = max((len(r[i]) for r in rows[1:]), default=1)
            types.append((c, sql_type(duck[c], longest)))
        load.append(load_block(t, "marts", header))
        build.append(typed_block(t, t, types))
        counts.append((t, len(rows) - 1))
    for src, dst in CALENDAR.items():                         # already landed by 02_load_raw.sql
        with (ROOT / "data" / "raw" / f"{src}.csv").open(newline="") as f:
            rows = list(csv.reader(f))
        duck = dict(con.execute(f"SELECT column_name, data_type FROM information_schema.columns "
                                f"WHERE table_schema = 'staging' AND table_name = 'stg_{dst}'").fetchall())
        types = [(c, sql_type(duck[c], max(len(r[i]) for r in rows[1:]))) for i, c in enumerate(rows[0])]
        build.append(typed_block(src, dst, types))
    build.append("\nPRINT 'Built fc: " + ", ".join(t for t, _ in counts) + ", report_calendar, report_quarter';\nGO\n")
    (ROOT / "sqlserver" / "02b_load_forecast.sql").write_text("".join(load))
    (ROOT / "sqlserver" / "03e_build_dw_forecast.sql").write_text("".join(build))
    print("Wrote sqlserver/02b_load_forecast.sql and sqlserver/03e_build_dw_forecast.sql")
    for t, n in counts:
        print(f"   {t:<32}{n:>9,} rows")


if __name__ == "__main__":
    main()
