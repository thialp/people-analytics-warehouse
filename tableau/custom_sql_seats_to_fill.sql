/*
  custom_sql_seats_to_fill.sql
  Tableau Custom SQL for Dashboard #5, Seats to Fill: FTE hiring forecast against plan (SQL Server,
  database ArcadiaHR). ONE data source for the whole page, so one In Scope calculation (the rail's
  organisation and location selections) filters every card. About 400,000 rows.

  Six row types, never summed together: filter row_type in every calculation.
    Quarter    department x office x quarter, 20 history quarters and the 4 forward ones
               (fc.mart_pid_fill_quarter): opened, filled, vacant at the end, and the Budget
               allocated to the office (planned_net_new, planned_backfills). Forward quarters
               carry the plan only.
    Draw       forward quarter x department x office x draw (fc.mart_pid_forecast_draws): one
               simulated future each. Sum a measure over the selection per draw, then take the
               percentiles across draws for the likely range.
    Survival   approval quarter x department x office x level band x requisition type x ten-day
               period (fc.mart_fill_survival): at_risk and sv_filled for the Kaplan-Meier curve,
               EXP(RUNNING_SUM(LN(1 - SUM(sv_filled) / SUM(at_risk)))).
    Backtest   backtest origin x target quarter x department x office (fc.mart_pid_forecast_backtest):
               forecast means and variances (they add up over a selection) and the actuals.
    Accuracy   backtest origin x target quarter, all of Arcadia (fc.mart_pid_forecast_accuracy): the
               P10, P50 and P90 against the actual. No department or office.
    CW budget  fiscal year x function (fc.mart_cw_budget_function): the contingent budget line.

  Every row carries the report calendar's labels (report_as_of_label, current_fiscal_year_label,
  forward_fiscal_year_label, forward_period_label) and quarter_offset / fy_offset (0 = the quarter or
  year ending on the report date, +1 forward): parameters store offsets, never years, so the page
  rolls forward when the report date does. Executive officers are excluded upstream.

  Checked by sqlserver/check_tsql_in_duckdb.py and sqlserver/17_validate_seats_to_fill.sql.
  Tableau rules: one SELECT, no CTEs, no ORDER BY, block comments only.
  Arcadia Systems is fictional; all data is synthetic.
*/
